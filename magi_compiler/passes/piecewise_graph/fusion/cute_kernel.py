"""CuTe DSL GEMM with fused in-kernel epilogue for Hopper (SM90+).

Design
------
The key insight is that WGMMA accumulates results into register files (``tRS_rD``).
Before those registers are written to shared/global memory, we can apply elementwise
epilogue operations (activation, bias-add, scale, …) *in-place on the register
values* — completely avoiding the extra read-back from global memory that a
separate Triton epilogue pass would require.

Concretely, inside the CuTe kernel's epilogue loop:

  for epi_idx in range_constexpr(epi_tile_num):
      for epi_v in range_constexpr(size_tRS_rD):
          tRS_rD[epi_v] = tRS_rAcc[epi_idx * size_tRS_rD + epi_v]

      acc_vec = tRS_rD.load()          # FP32 register tensor
      # ── INJECT: fused epilogue ──────────────────────────────────
      acc_vec = self._apply_epilogue(acc_vec)
      # ────────────────────────────────────────────────────────────
      tRS_rD_out.store(acc_vec.to(self.c_dtype))
      ...

``HopperWgmmaGemmEpilogueFusedKernel`` subclasses
``HopperWgmmaGemmPersistentKernel`` and overrides ``kernel()`` with this
single extra line, plus the mechanism to supply ``_apply_epilogue``.

Epilogue representation
-----------------------
The epilogue is described by two complementary representations:

1. **Triton epilogue string** (``epilogue_code``) — already generated by
   ``MatmulCustomEpilogueFusionPass._try_fuse_custom_chain``.  We *parse* this
   string to drive the CuTe DSL code that runs inside the kernel.

2. **CuTe DSL epilogue callable** (``epilogue_fn``) — a Python callable that
   accepts a ``TensorSSA`` (FP32 accumulator tile) and returns a transformed
   ``TensorSSA`` of the same shape.  It is invoked at ``@cute.jit`` trace time
   so it must only use CuTe DSL primitives (``cute.exp``, ``cute.tanh``, …).

The ``_build_epilogue_fn`` factory converts the Triton epilogue string into a
CuTe DSL callable.  It covers the same op set that ``triton_kernels.py``
supports so all fused chains are handled correctly.

Extras (bias tensors, etc.)
---------------------------
The Triton string may reference ``Extra_0_ptr``, ``Extra_1_ptr``, … which are
additional (bias / scale) tensors.  At CuTe DSL level these arrive as plain
FP16 1-D or 2-D GPU tensors; the epilogue builder injects loads via a small
helper that reads the correct row of the extra tensor for the current
``epi_idx`` subtile.

Fallback
--------
On non-Hopper or when ``cutlass-dsl`` is unavailable the module falls back to
the pure-Triton path (``matmul_custom_epilogue`` from ``triton_kernels.py``).
"""

